"""Offline illustrative lifecycle. ALL candles, quotes, risk and fills simulated.

Uses the tested in-memory adapter. Never constructs a real broker transport.
python tools/phase3a_manager_demo.py OUTPUT.json
"""
import copy
import json
from pathlib import Path
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT),str(ROOT/'tests')]
from test_directional_position_manager import setup,propose,level,exit_fill
from directional_position_manager import Manager


def run():
    steps=[]
    with tempfile.TemporaryDirectory() as folder:
        m,b,adapter=setup(Path(folder))
        def record(label,**extra):
            steps.append(dict(step=label,at_ms=b['observed_ms'],state=copy.deepcopy(m.get('one')),**extra))
        record('Entry fills confirmed; native SL/TP observed')
        p=propose(m,b,{'partial':level(110.,quantity=1)})
        record('Closed candle + validated synthetic quote/risk → research REDUCE',proposal=p)
        intent=m.request('one',p,adapter,b['observed_ms'])
        record('Reduction ACK; quantity remains TWO until fill',intent=intent)
        exit_fill(b,1,110.,14)
        m.reconcile('one',b,b['observed_ms'])
        record('Partial fill + simulated atomic resize → ONE protected contract')
        m=Manager(m.connect,m.binding)
        record('Restart: persisted remaining quantity and bracket recovered')
        p=propose(m,b,{'runner':level(130.)})
        intent=m.request('one',p,adapter,b['observed_ms'])
        record('Runner target ACK; old target still authoritative',proposal=p,intent=intent)
        b['protective_orders'][0]['price']=130.;b['observed_ms']+=100
        b['command_reports']=[dict(command_id=77,confirmed=True,rejected=False)]
        m.reconcile('one',b,b['observed_ms'])
        record('Exact command report + matching protected order → RUNNER')
        exit_fill(b,1,130.,12);m.reconcile('one',b,b['observed_ms'])
        record('Runner fill + sibling cancellation + simulated fees → CLOSED')
    return dict(kind='SYNTHETIC_PROTOCOL_DEMO_NOT_PRODUCTION_OR_BACKTEST',
        fixture_clock='Synthetic milliseconds; not historical NY timestamps.',
        entry_review='Phase 2A/2B integration unchanged; no AI review is generated by this demo.',
        rule_notice='1R partial of one out of two, then 3R runner is an illustration, NOT a chosen live policy.',
        protection_notice='Atomic resize belongs only to the simulator; CrossTrade capability is NOT verified.',steps=steps)


if __name__=='__main__':
    path=Path(sys.argv[1]);path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(run(),indent=2,allow_nan=False)+'\n');print(path)
